const SIDE_EYES = {
  shut: [['FFFF', 9, 6], ['FFoo', 9, 7]],
  squeeze: [['FFoF', 9, 6], ['FFFo', 9, 7]],
  swirl: [['Foo', 10, 6], ['FFo', 10, 7]],
};
const FRONT_EYES = {
  shut: [['FFFFFF', 4, 6], ['ooFFoo', 5, 7]],
  happy: [['FoFFoF', 5, 6], ['oFooFo', 5, 7]],
};
function headOf(who, view = 'side', eyes = null) {
  const base = view === 'front' ? HEAD_FRONT[who] : HEAD_SIDE[who];
  const patches = eyes ? (view === 'front' ? FRONT_EYES : SIDE_EYES)[eyes] : null;
  return patches ? patches.reduce((rows, [art, x, y]) => stamp(rows, [art], x, y), base) : base;
}

