// The robe rig (COMBAT.md §14.2): the robed Wayfarers' proportions, 16 × 18 at rest with no legs (a
// hem on an ink row), in a 32 × 28 fight frame with the hem at (16, 26). One body serves the Scribe
// (`claude`) and the Artificer (`codex`): it's drawn in placeholder tones that each look fills in,
//   A robe · D robe shade · F face and hands · H hood shine · T the Scribe's cream nib emblem
//   X the Artificer's cream sash · I the Artificer's book (robe on the Scribe)
// and each of them has their own head (her round hood, his peaked one) and their own held things,
// eight each (her quill, book, pages, ink and letter; his wrench, schematic, gear, rivet and tinkering).
//
// Pose fields as the coat rig's (rows, at, anchors), plus `items`: held things stamped over the body
// at grid points, which the wear mask keeps undressed, and `thumb`, where the Clay Likeness's
// thumbprint goes. A pose built per person is registered as `claude:<pose>` and `codex:<pose>`.
import { grid, stamp } from '../sprites.js';

